const fs = require("fs");
const COLORS = ["slate","gray","zinc","neutral","stone","red","orange","amber","yellow","lime","green","emerald","teal","cyan","sky","blue","indigo","violet","purple","fuchsia","pink","rose"];
// Bright hues need dark text on a solid fill for legible contrast.
const LIGHT = new Set(["amber","yellow","lime"]);

// White text sits on the lightest shade that clears 4.5:1 (scripts/solid-shades),
// one step darker on hover. Dark mode keeps its shape: one step deeper at rest,
// back to that shade on hover, never lighter than it (6.19.1; it was 500 / 600,
// which is 2.47:1 for emerald).
const SHADE = require("./solid-shades.cjs");
const solid = (c) => {
  if (LIGHT.has(c)) {
    return `bg-${c}-400 text-${c}-950 border border-${c}-500 hover:bg-${c}-500 dark:bg-${c}-300 dark:text-${c}-950 dark:border-${c}-400 dark:hover:bg-${c}-400`;
  }
  const s = SHADE[c];
  const d = s + 100;
  return `bg-${c}-${s} text-white border border-${c}-${d} hover:bg-${c}-${d} dark:bg-${c}-${d} dark:border-${c}-${s} dark:hover:bg-${c}-${s}`;
};
const ghost = (c) => `bg-transparent text-${c}-600 hover:bg-${c}-50 dark:text-${c}-400 dark:hover:bg-${c}-950/50`;

// `color="brand"`: the host's colour, from CSS variables (see styles.css).
const BRAND_NOTE = [
  "  // The host's colour, from CSS variables -- no dark: variant, because a",
  "  // host that themes per mode scopes the variables themselves.",
];
const BRAND = {
  solid: "bg-brand text-brand-contrast border border-brand hover:bg-brand-hover",
  ghost: "bg-transparent text-brand hover:bg-brand/10",
};

const rec = (fn, brand) =>
  "{\n" + [...BRAND_NOTE, `  brand: "${brand}",`, ...COLORS.map((c) => `  ${c}: "${fn(c)}",`)].join("\n") + "\n}";

const out = `// AUTO-GENERATED by scripts/gen-button-colors — do not edit by hand.
// Literal Tailwind class strings for every color in the v4 palette so the
// scanner can detect them in the published dist (template-built names are
// invisible to Tailwind's JIT). Regenerate after changing the palette.
import type { Color } from "../../utils/types";

export const buttonColorClasses: Record<Color, string> = ${rec(solid, BRAND.solid)};

export const buttonGhostClasses: Record<Color, string> = ${rec(ghost, BRAND.ghost)};
`;
fs.writeFileSync(__dirname + "/../src/components/Button/Button.colors.ts", out);
console.log("wrote Button.colors.ts (brand + " + COLORS.length + " colors × 2 maps)");
