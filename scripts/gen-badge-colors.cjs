const fs = require("fs");
const COLORS = ["slate","gray","zinc","neutral","stone","red","orange","amber","yellow","lime","green","emerald","teal","cyan","sky","blue","indigo","violet","purple","fuchsia","pink","rose"];
// Bright hues need dark text on a solid fill for legible contrast.
const LIGHT = new Set(["amber","yellow","lime"]);

// White text: 600 in light and 500 in dark, but never lighter than the shade
// that clears 4.5:1 (scripts/solid-shades). Where both modes land on the same
// shade, no dark: class is emitted (6.19.1).
const SHADE = require("./solid-shades.cjs");
const solid = (c) => {
  if (LIGHT.has(c)) return `bg-${c}-400 text-${c}-950 dark:bg-${c}-300 dark:text-${c}-950`;
  const light = Math.max(600, SHADE[c]);
  const dark = Math.max(500, SHADE[c]);
  return light === dark ? `bg-${c}-${light} text-white` : `bg-${c}-${light} text-white dark:bg-${c}-${dark}`;
};
const outline = (c) => `border border-${c}-300 text-${c}-700 dark:border-${c}-600 dark:text-${c}-300`;
const soft = (c) => `bg-${c}-100 text-${c}-700 dark:bg-${c}-900/30 dark:text-${c}-300`;
const dot = (c) => `bg-${c}-500`;

// `color="brand"`: the host's colour, from CSS variables (see styles.css).
const BRAND_NOTE = [
  "  // The host's colour, from CSS variables -- no dark: variant, because a",
  "  // host that themes per mode scopes the variables themselves.",
];
const BRAND = {
  solid: "bg-brand text-brand-contrast",
  outline: "border border-brand/40 text-brand",
  soft: "bg-brand/10 text-brand",
  dot: "bg-brand",
};

const rec = (fn, brand) =>
  "{\n" + [...BRAND_NOTE, `  brand: "${brand}",`, ...COLORS.map((c) => `  ${c}: "${fn(c)}",`)].join("\n") + "\n}";

const out = `// AUTO-GENERATED by scripts/gen-badge-colors — do not edit by hand.
// Literal Tailwind class strings for every color in the v4 palette so the
// scanner can detect them in the published dist (template-built names are
// invisible to Tailwind's JIT). Regenerate after changing the palette.
import type { Color } from "../../utils/types";

export const badgeSolid: Record<Color, string> = ${rec(solid, BRAND.solid)};

export const badgeOutline: Record<Color, string> = ${rec(outline, BRAND.outline)};

export const badgeSoft: Record<Color, string> = ${rec(soft, BRAND.soft)};

export const badgeDot: Record<Color, string> = ${rec(dot, BRAND.dot)};
`;
fs.writeFileSync(__dirname + "/../src/components/Badge/Badge.colors.ts", out);
console.log("wrote Badge.colors.ts (brand + " + COLORS.length + " colors × 4 maps)");
